tbls = [m for m in re.finditer(r"<w:tbl>.*?</w:tbl>", x, re.S)]
m = tbls[1]
tbl = m.group(0)
rows = re.findall(r"<w:tr[ >].*?</w:tr>", tbl, re.S)
new = tbl
for r in rows[:-1]:
    r2 = re.sub(r'<w:keepNext w:val="0"/>', '<w:keepNext w:val="1"/>', r)
    r2 = re.sub(r"<w:pPr>(?!<w:pStyle)(?!<w:keepNext)", "<w:pPr><w:keepNext/>", r2)
    new = new.replace(r, r2, 1)
x = x[:m.start()] + new + x[m.end():]
files["word/document.xml"] = x.encode("utf-8")
